#!/usr/bin/env python3
"""Rebuild the approved compact flash clock from its verified export (stdlib only)."""
import argparse
import base64
import gzip
import hashlib
import json
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FOLDER = ROOT / 'assets/clock77'
OUTPUT = ROOT / 'firmware/RPG_POKET_2/ClockArtData.h'


def sha(data):
    return hashlib.sha256(data).hexdigest()


def rgb(color):
    return ((color >> 11) * 255 // 31,
            ((color >> 5) & 63) * 255 // 63, (color & 31) * 255 // 31)


def build():
    metadata = json.loads((FOLDER / 'export.json').read_text())
    assert metadata['width'] == 240 and metadata['height'] == 320
    assert metadata['palette_entries'] == 256 and metadata['flash_bytes'] == 77312
    assert sha((FOLDER / metadata['source_file']).read_bytes()) == metadata['source_png_sha256']
    source = gzip.decompress(base64.b64decode((FOLDER / metadata['source_rgb565_file']).read_bytes()))
    assert len(source) == 153600 and sha(source) == metadata['source_rgb565_sha256']
    encoded = (FOLDER / metadata['export_file']).read_bytes()
    assert sha(encoded) == metadata['export_sha256']
    data = gzip.decompress(base64.b64decode(encoded))
    assert len(data) == 77312 and sha(data) == metadata['decoded_sha256']
    palette, plane = struct.unpack('<256H', data[:512]), data[512:]
    reference = b''.join(struct.pack('<H', palette[index]) for index in plane)
    assert sha(reference) == metadata['reference_rgb565_sha256']
    before, after = struct.unpack('<76800H', source), struct.unpack('<76800H', reference)
    errors = [abs(x-y) for a, b in zip(before, after) for x, y in zip(rgb(a), rgb(b))]
    metrics = dict(mean_absolute_channel_error_8bit=round(sum(errors)/len(errors), 6),
                   root_mean_square_channel_error_8bit=round((sum(e*e for e in errors)/len(errors))**.5, 6),
                   maximum_channel_error_8bit=max(errors),
                   unchanged_rgb565_pixels=sum(a == b for a, b in zip(before, after)),
                   total_pixels=76800)
    assert metrics == metadata['quantization']
    header = ('#pragma once\n#include <stdint.h>\n'
              '// Generated by tools/prepare_clock_art.py from the approved blank.\n'
              '// Opaque idx8 plane and RGB565 palette live in flash, including fallback.\n'
              'namespace clockArt {\nconstexpr unsigned W=240,H=320;\n'
              'inline constexpr uint16_t palette[256]={' + ','.join(map(str, palette)) + '};\n'
              'inline constexpr uint8_t plane[W*H]={\n' +
              ',\n'.join(','.join(map(str, plane[i:i+64])) for i in range(0, len(plane), 64)) +
              '\n};\nstatic_assert(sizeof(plane)+sizeof(palette)==77312,"Clock flash geometry");\n}\n')
    return header, reference, metadata


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--extract-reference', type=Path)
    args = parser.parse_args()
    header, reference, metadata = build()
    if args.check:
        assert OUTPUT.read_text() == header, 'Stale clock output'
    else:
        OUTPUT.write_text(header)
    if args.extract_reference:
        args.extract_reference.parent.mkdir(parents=True, exist_ok=True)
        args.extract_reference.write_bytes(reference)
    print('PASS: approved clock 77312 flash bytes; source/export/reference hashes; '
          'RGB565 quantization metrics: ' + json.dumps(metadata['quantization'], sort_keys=True))


if __name__ == '__main__':
    main()
