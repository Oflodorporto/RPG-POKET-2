"""Deterministically prepare compact, regular-icosahedron orientations."""
import argparse
import math
import pathlib
p=pathlib.Path(__file__).resolve().parents[1]/'firmware/RPG_POKET_2/D20Mesh.h'
phi=(1+math.sqrt(5))/2
verts=[(-1,phi,0),(1,phi,0),(-1,-phi,0),(1,-phi,0),(0,-1,phi),(0,1,phi),(0,-1,-phi),(0,1,-phi),(phi,0,-1),(phi,0,1),(-phi,0,-1),(-phi,0,1)]
faces=[(0,11,5),(0,5,1),(0,1,7),(0,7,10),(0,10,11),(1,5,9),(5,11,4),(11,10,2),(10,7,6),(7,1,8),(3,9,4),(3,4,2),(3,2,6),(3,6,8),(3,8,9),(4,9,5),(2,4,11),(6,2,10),(8,6,7),(9,8,1)]
def add(a,b):return tuple(x+y for x,y in zip(a,b))
def sub(a,b):return tuple(x-y for x,y in zip(a,b))
def mul(a,s):return tuple(x*s for x in a)
def dot(a,b):return sum(x*y for x,y in zip(a,b))
def norm(v):return mul(v,1/math.sqrt(dot(v,v)))
def cross(a,b):return (a[1]*b[2]-a[2]*b[1],a[2]*b[0]-a[0]*b[2],a[0]*b[1]-a[1]*b[0])
# Pair opposite faces to sum21. All numerals remain attached to fixed physical faces.
centers=[norm(add(add(verts[a],verts[b]),verts[c])) for a,b,c in faces]
nums=[0]*20;n=1
for i in range(20):
 if nums[i]:continue
 j=min(range(20),key=lambda j:dot(centers[i],centers[j]));nums[i]=n;nums[j]=21-n;n+=1
rows=[]
for value in range(1,21):
 face=nums.index(value);a,b,c=faces[face];z=centers[face];y=norm(sub(z,verts[a]));x=norm(cross(y,z));y=cross(z,x)
 # Face top vertex upward. Tilt slightly for richer depth, with every winning face upright.
 az=-0.07;ay=0.10
 row=[]
 for v in verts:
  v=norm(v);xx,yy,zz=dot(v,x),dot(v,y),dot(v,z)
  xx,zz=xx*math.cos(ay)+zz*math.sin(ay),zz*math.cos(ay)-xx*math.sin(ay)
  yy,zz=yy*math.cos(az)-zz*math.sin(az),zz*math.cos(az)+yy*math.sin(az)
  row.append(tuple(round(q*120) for q in (xx,yy,zz)))
 rows.append(row)
s='''#pragma once
#include <stdint.h>
// Regular icosahedron: 12 shared vertices, 30 edges, 20 triangular faces.
// Generated by tools/prepare_d20_mesh.py; signed unit vectors use scale 120.
// Each row points its actual numbered face forward; no face label is swapped.
namespace d20Ui {
struct Vertex { int16_t x,y,z; };
struct Face { uint8_t a,b,c,value; };
constexpr Face faces[20]={\n'''
s+=',\n'.join(' {%d,%d,%d,%d}'%(*f,v) for f,v in zip(faces,nums))+'\n};\nconstexpr int8_t settled[20][12][3]={\n'
s+=',\n'.join(' {'+','.join('{%d,%d,%d}'%v for v in row)+'}' for row in rows)+'\n};\n'
s+='constexpr int16_t sine[64]={'+','.join(str(round(math.sin(i*math.pi/32)*256)) for i in range(64))+'};\n}\n'
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true", help="verify checked-in geometry without writing")
args = parser.parse_args()
assert sorted(nums) == list(range(1, 21))
for i, value in enumerate(nums):
 opposite = min(range(20), key=lambda j: dot(centers[i], centers[j]))
 assert value + nums[opposite] == 21
 assert dot(centers[i], centers[opposite]) < -0.999999
if args.check:
 assert p.read_text() == s, "D20 mesh differs; regenerate with tools/prepare_d20_mesh.py"
else:
 p.write_text(s)
print("PASS: regular 12-vertex/20-face mesh; unique1..20 and all opposite face pairs sum21")
