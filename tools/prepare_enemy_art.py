#!/usr/bin/env python3
"""Deterministically replace enemy-only PKA1 slots with audited 4-bit exports.

Uses Python's standard library, archived baseline metadata and the unchanged
original compressed packs. Rebuilding never reads the generated AssetCatalog.h
as its baseline. No artwork generation, resampling or dependency installation.
"""
from dataclasses import dataclass
from pathlib import Path
import argparse
import gzip
import hashlib
import io
import json
import re
import struct
import sys
import tarfile
import zlib

sys.dont_write_bytecode = True

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'assets/enemies-original1'
POSES = ('idle', 'anticipation', 'attack', 'hurt')
FAMILIES = ('slash', 'bite', 'charge', 'claw', 'magic', 'pulse', 'crush')
RETIRED = tuple(range(92, 123)) + tuple(range(401, 417)) + tuple(range(459, 464)) + tuple(range(480, 488))
BODY_SLOTS = RETIRED + tuple(range(488, 544))
EFFECT_SLOTS = tuple(range(544, 600))
ENEMY_PALETTES = tuple(range(600, 629))
EFFECT_PALETTES = tuple(range(629, 636))
# Preserve the published 636-entry pack as a strict historical fixture.
CATALOG_PATH = ASSETS / 'generated/AssetCatalog636.h'
DESCRIPTOR_PATH = ROOT / 'firmware/RPG_POKET_2/EnemyArtCatalog.h'
REPORT_PATH = ASSETS / 'integration_manifest.json'
# Keep the original implementation's storage bounds exactly unchanged.
CATALOG_TRAILER = '''inline uint8_t* artMemory=nullptr;
inline const uint8_t* assetBytes(unsigned id){return artMemory+assetMeta[id].offset;}
inline void makeFallback(){for(const auto& m:assetMeta)for(unsigned y=0;y<m.h;++y)for(unsigned x=0;x<m.w;++x)for(unsigned b=0;b<m.elem;++b)artMemory[m.offset+(y*m.w+x)*m.elem+b]=artFallback[m.fallback+((y*m.th/m.h)*m.tw+x*m.tw/m.w)*m.elem+b];}
'''


def require(condition, message):
    if not condition:
        raise ValueError(message)


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def json_text(value):
    return json.dumps(value, ensure_ascii=False, indent=2) + '\n'


def verify_file(data, record, label):
    require(len(data) == record['bytes'], f'{label}: byte length mismatch')
    require(sha256(data) == record['sha256'], f'{label}: SHA-256 mismatch')


def load_exports():
    provenance = json.loads((ASSETS / 'provenance.json').read_text())
    for path, record in provenance['retained_source_files'].items():
        verify_file((ASSETS / path).read_bytes(), record, path)
    info = provenance['exports_bundle']
    bundle = (ASSETS / info['file']).read_bytes()
    verify_file(bundle, info, info['file'])
    files = {}
    # Read in memory; no archive path is ever extracted into the filesystem.
    with tarfile.open(fileobj=io.BytesIO(bundle), mode='r:gz') as tf:
        for member in tf.getmembers():
            require(member.isfile() and member.name in info['files'], 'Unexpected export archive member')
            require(member.name not in files, 'Duplicate export archive member')
            data = tf.extractfile(member).read()
            verify_file(data, info['files'][member.name], member.name)
            files[member.name] = data
    require(set(files) == set(info['files']), 'Missing export archive member')
    original = json.loads((ASSETS / 'source/CHECKSUMS.json').read_text())['files']
    for path, data in files.items():
        verify_file(data, original[path], path)
    roster = json.loads((ASSETS / 'source/exports/roster_manifest.json').read_text())
    return files, roster['enemies']


def decode_idx4(encoded, palette):
    require(len(palette) == 32, 'Palette must contain 16 RGB565LE colors')
    require(palette[:2] == b'\x1f\xf8', 'Palette index zero must be transparent')
    # A nonzero index must not become transparent when drawn with the RGB key.
    require(all(palette[i:i + 2] != b'\x1f\xf8' for i in range(2, 32, 2)), 'Opaque palette-key collision')
    colors = [palette[i:i + 2] for i in range(0, 32, 2)]
    return b''.join(colors[value >> 4] + colors[value & 15] for value in encoded)


def parse_catalog(text):
    """Small independent parser for tests; never used as the baseline source."""
    body = re.search(r'constexpr AssetMeta assetMeta\[\]=\{(.*?)\n\};', text, re.S).group(1)
    rows = [tuple(map(int, row.split(','))) for row in re.findall(r'\{([\d,]+)\}', body)]
    fallback = re.search(r'constexpr uint8_t artFallback\[\]=\{(.*?)\n\};', text, re.S).group(1)
    fallback = re.sub(r'//[^\n]*', '', fallback)
    return rows, bytes(map(int, re.findall(r'\b\d+\b', fallback)))


def catalog_text(metadata, fallback, crc):
    lines = ['#pragma once', '#include <stdint.h>', '#include <stddef.h>',
             '// Generated by tools/prepare_enemy_art.py; original archives remain unchanged.',
             'struct AssetMeta {uint32_t offset;uint16_t w,h;uint32_t fallback;uint8_t tw,th,elem;};',
             f'constexpr uint32_t ART_BYTES={sum(m[1]*m[2]*m[6] for m in metadata)},ART_CRC=0x{crc:08x};',
             f'constexpr unsigned ART_COUNT={len(metadata)};', 'constexpr AssetMeta assetMeta[]={']
    lines += ['{' + ','.join(map(str, row)) + '},' for row in metadata]
    lines += ['};', 'constexpr uint8_t artFallback[]={']
    lines += [','.join(map(str, fallback[i:i + 40])) + ',' for i in range(0, len(fallback), 40)]
    lines += ['};', CATALOG_TRAILER.rstrip()]
    return '\n'.join(lines) + '\n'


def descriptor_text(enemies):
    lines = ['#pragma once', '#include <stdint.h>', '#include "AssetCatalog.h"',
             '// Generated from the immutable original roster. Gameplay IDs stay 0..28.',
             'namespace enemyArt {',
             'enum class Family:uint8_t {Slash,Bite,Charge,Claw,Magic,Pulse,Crush};',
             'enum class Anchor:uint8_t {Ground,Virtual};',
             'struct EnemyDescriptor {uint16_t poses[4],palette;int16_t anchorX,anchorY;Anchor anchor;Family family;};',
             'constexpr unsigned ENEMY_COUNT=29,POSE_COUNT=4,FAMILY_COUNT=7,FX_FRAMES=8;',
             'constexpr unsigned BODY_W=80,BODY_H=86,BODY_STRIDE=40,BODY_BYTES=3440;',
             'constexpr unsigned FX_W=32,FX_H=32,FX_STRIDE=16,FX_BYTES=512;',
             'constexpr unsigned PALETTE_COLORS=16,PALETTE_BYTES=32;',
             'constexpr uint16_t TRANSPARENT=0xf81f;',
             '// Every supplied body faces left. Dimensions are logical; AssetMeta stores byte planes.',
             'constexpr bool BODY_FACING_LEFT=true;',
             'constexpr EnemyDescriptor enemies[ENEMY_COUNT]={']
    for enemy in enemies:
        i = enemy['id']
        poses = ','.join(map(str, BODY_SLOTS[i * 4:i * 4 + 4]))
        x, y = enemy['root_anchor']
        anchor = 'Ground' if enemy['anchor_mode'] == 'ground' else 'Virtual'
        lines.append(f'  {{{{{poses}}},{600 + i},{x},{y},Anchor::{anchor},Family::{enemy["attack_kind"].title()}}}, // {i}: {enemy["slug"]}')
    lines += ['};', 'constexpr uint16_t effectFrames[FAMILY_COUNT][FX_FRAMES]={']
    for i, name in enumerate(FAMILIES):
        lines.append('  {' + ','.join(str(544 + i * 8 + f) for f in range(8)) + '}, // ' + name)
    lines += ['};', 'constexpr uint16_t effectPalettes[FAMILY_COUNT]={629,630,631,632,633,634,635};',
              '''constexpr bool validPlane(unsigned id,unsigned w,unsigned h) {
  return id<ART_COUNT && assetMeta[id].w==w && assetMeta[id].h==h &&
    assetMeta[id].elem==1 && assetMeta[id].tw==1 && assetMeta[id].th==1 &&
    assetMeta[id].offset+w*h<=ART_BYTES &&
    assetMeta[id].fallback<sizeof(artFallback) && artFallback[assetMeta[id].fallback]==0;
}
constexpr bool validPalette(unsigned id) {
  return id<ART_COUNT && assetMeta[id].w==PALETTE_COLORS && assetMeta[id].h==1 &&
    assetMeta[id].elem==2 && assetMeta[id].tw==PALETTE_COLORS && assetMeta[id].th==1 &&
    assetMeta[id].offset+PALETTE_BYTES<=ART_BYTES &&
    assetMeta[id].fallback+PALETTE_BYTES<=sizeof(artFallback) &&
    artFallback[assetMeta[id].fallback]==0x1f && artFallback[assetMeta[id].fallback+1]==0xf8;
}
constexpr bool validCatalog() {
  if(ART_COUNT<636 || sizeof(assetMeta)/sizeof(assetMeta[0])!=ART_COUNT) return false;
  unsigned end=0;
  for(unsigned i=0;i<ART_COUNT;++i) {
    const auto& m=assetMeta[i];
    if(m.offset!=end || !m.w || !m.h || !m.tw || !m.th || (m.elem!=1 && m.elem!=2)) return false;
    if(m.fallback+unsigned(m.tw)*m.th*m.elem>sizeof(artFallback)) return false;
    end+=unsigned(m.w)*m.h*m.elem;
    if(end>ART_BYTES) return false;
  }
  return end==ART_BYTES;
}
constexpr bool validDescriptors() {
  for(unsigned i=0;i<ENEMY_COUNT;++i) {
    const auto& e=enemies[i];
    if(e.palette!=600+i || !validPalette(e.palette) || unsigned(e.family)>=FAMILY_COUNT ||
       e.anchorX<0 || e.anchorX>=int(BODY_W) || e.anchorY<0 || e.anchorY>=int(BODY_H)) return false;
    for(unsigned p=0;p<POSE_COUNT;++p) {
      if(!validPlane(e.poses[p],BODY_STRIDE,BODY_H)) return false;
      for(unsigned j=0;j<i*POSE_COUNT+p;++j) if(enemies[j/POSE_COUNT].poses[j%POSE_COUNT]==e.poses[p]) return false;
    }
  }
  for(unsigned k=0;k<FAMILY_COUNT;++k) {
    if(effectPalettes[k]!=629+k || !validPalette(effectPalettes[k])) return false;
    for(unsigned f=0;f<FX_FRAMES;++f) if(effectFrames[k][f]!=544+k*FX_FRAMES+f ||
      !validPlane(effectFrames[k][f],FX_STRIDE,FX_H)) return false;
  }
  return true;
}
static_assert(BODY_W/2==BODY_STRIDE && BODY_STRIDE*BODY_H==BODY_BYTES,"Enemy index plane dimensions");
static_assert(FX_W/2==FX_STRIDE && FX_STRIDE*FX_H==FX_BYTES,"Effect index plane dimensions");
static_assert(validCatalog(),"Asset catalog bounds and non-overlap");
static_assert(validDescriptors(),"Typed compact enemy descriptor contract");
} // namespace enemyArt''']
    return '\n'.join(lines) + '\n'


@dataclass
class BuildResult:
    pack: bytes
    metadata: list
    fallback: bytes
    catalog: str
    descriptors: str
    report: dict


def build(baseline_pack=None):
    baseline = json.loads((ASSETS / 'baseline/catalog.json').read_text())
    for path, info in baseline['archives'].items():
        verify_file((ROOT / path).read_bytes(), info, path)
    if baseline_pack is None:
        from unpack_art import reconstruct_legacy_pack
        baseline_pack = reconstruct_legacy_pack()
    old = baseline_pack[16:]
    require(struct.unpack('<4sIII', baseline_pack[:16]) == (b'PKA1', 6991936, 0x53dcc3a5, 488), 'Wrong baseline envelope')
    require(len(old) == 6991936 and zlib.crc32(old) == 0x53dcc3a5, 'Wrong baseline payload')
    old_meta = baseline['metadata']
    require(len(old_meta) == 488, 'Wrong archived baseline metadata count')
    old_fallback = gzip.decompress((ASSETS / 'baseline/fallback.bin.gz').read_bytes())
    require(len(old_fallback) == baseline['fallback_bytes'] and sha256(old_fallback) == baseline['fallback_sha256'], 'Wrong baseline fallback')
    require(sum(old_meta[i][1] * old_meta[i][2] * old_meta[i][6] for i in RETIRED) == 759360, 'Wrong retired enemy byte count')
    old_end = 0
    for m in old_meta:
        offset, w, h, fb, tw, th, elem = m
        require(offset == old_end and w and h and tw and th and elem in (1, 2), 'Invalid archived baseline metadata')
        old_end += w * h * elem
        require(fb + tw * th * elem <= len(old_fallback), 'Archived fallback out of bounds')
    require(old_end == len(old), 'Archived catalog does not cover baseline payload')
    exports, enemies = load_exports()
    require([e['id'] for e in enemies] == list(range(29)), 'Roster gameplay IDs changed')
    replacement = {}
    replacement_meta = {}
    source_paths = {}
    reference_records = []
    png_hashes = []
    for enemy in enemies:
        i = enemy['id']
        require(enemy['frame_size'] == [80, 86] and tuple(enemy['pose_order']) == POSES, 'Enemy dimensions/order changed')
        require(enemy['facing'] == 'left' and enemy['anchor_mode'] in ('ground', 'center'), 'Unexpected facing/anchor')
        require(enemy['attack_kind'] in FAMILIES, 'Unexpected effect family')
        require(all(isinstance(v, int) for v in enemy['root_anchor']), 'Non-integer exported root anchor')
        prefix = f'exports/enemies/{i:02d}_{enemy["slug"]}'
        palette = exports[prefix + '/palette.rgb565le']
        require(list(struct.unpack('<16H', palette)) == [int(v, 16) for v in enemy['palette_rgb565']], 'Enemy palette differs from manifest')
        for p, name in enumerate(POSES):
            slot = BODY_SLOTS[i * 4 + p]
            path = prefix + '/' + name + '.idx4'
            encoded = exports[path]
            reference = exports[prefix + '/' + name + '.rgb565le']
            require(len(encoded) == 3440 and len(reference) == 13760, 'Enemy export length changed')
            require(decode_idx4(encoded, palette) == reference, f'Pixel mismatch: enemy {i} {name}')
            png_hashes.append(sha256(exports[prefix + '/' + name + '.png']))
            replacement[slot], replacement_meta[slot], source_paths[slot] = encoded, (40, 86, 1, 1, 1), path
            reference_records.append({'asset_id': slot, 'reference': prefix + '/' + name + '.rgb565le', 'sha256': sha256(reference)})
        replacement[600 + i] = palette
        replacement_meta[600 + i] = (16, 1, 16, 1, 2)
        source_paths[600 + i] = prefix + '/palette.rgb565le'
    require(len(set(png_hashes)) == 116, 'Enemy pose PNGs are not all distinct')
    for k, kind in enumerate(FAMILIES):
        prefix = 'exports/effects/' + kind
        palette = exports[prefix + '/palette.rgb565le']
        manifest = json.loads((ASSETS / 'source' / prefix / 'manifest.json').read_text())
        require(manifest['size'] == [32, 32] and manifest['frame_count'] == 8, 'Effect dimensions/count changed')
        require(list(struct.unpack('<16H', palette)) == manifest['palette_rgb565'], 'Effect palette differs from manifest')
        for f in range(8):
            slot = 544 + k * 8 + f
            path = prefix + f'/{f:02d}.idx4'
            encoded = exports[path]
            reference = exports[prefix + f'/{f:02d}.rgb565le']
            require(len(encoded) == 512 and len(reference) == 2048, 'Effect export length changed')
            require(decode_idx4(encoded, palette) == reference, f'Pixel mismatch: {kind} {f}')
            replacement[slot], replacement_meta[slot], source_paths[slot] = encoded, (16, 32, 1, 1, 1), path
            reference_records.append({'asset_id': slot, 'reference': prefix + f'/{f:02d}.rgb565le', 'sha256': sha256(reference)})
        replacement[629 + k], replacement_meta[629 + k] = palette, (16, 1, 16, 1, 2)
        source_paths[629 + k] = prefix + '/palette.rgb565le'
    require(len(replacement) == 208 and sum(map(len, replacement.values())) == 428864, 'Wrong replacement budget')
    payload, fallback, metadata, records = bytearray(), bytearray(), [], []
    zero_fallback = None
    unchanged = 0
    for i in range(636):
        if i in replacement:
            data = replacement[i]
            w, h, tw, th, elem = replacement_meta[i]
            if elem == 1:
                if zero_fallback is None:
                    zero_fallback = len(fallback)
                    fallback.append(0)
                fb = zero_fallback
            else:
                fb = len(fallback)
                fallback.extend(data)
            record = {'id': i, 'source': source_paths[i]}
        else:
            require(i < 488 and i not in RETIRED, 'Unmapped asset slot')
            offset, w, h, old_fb, tw, th, elem = old_meta[i]
            data = old[offset:offset + w * h * elem]
            fb = len(fallback)
            fallback.extend(old_fallback[old_fb:old_fb + tw * th * elem])
            record = {'id': i, 'unchanged_from_baseline': True}
            unchanged += 1
        require(len(data) == w * h * elem, f'Asset {i} stored length mismatch')
        metadata.append((len(payload), w, h, fb, tw, th, elem))
        record.update(offset=len(payload), bytes=len(data), sha256=sha256(data))
        records.append(record)
        payload.extend(data)
    require(unchanged == 428 and len(payload) == 6661440, 'Wrong final asset layout')
    # Verify the actual assembled package, not only the input-copy operation.
    for i in range(488):
        if i not in RETIRED:
            a, b = old_meta[i], metadata[i]
            n = a[1] * a[2] * a[6]
            require(payload[b[0]:b[0] + n] == old[a[0]:a[0] + n], f'Non-enemy asset {i} changed')
            require(tuple(a[1:3] + a[4:]) == b[1:3] + b[4:], f'Non-enemy metadata {i} changed')
            nfb = a[4] * a[5] * a[6]
            require(fallback[b[3]:b[3] + nfb] == old_fallback[a[3]:a[3] + nfb], f'Non-enemy fallback {i} changed')
    crc = zlib.crc32(payload)
    pack = struct.pack('<4sIII', b'PKA1', len(payload), crc, len(metadata)) + payload
    report = {'schema': 1, 'format': 'PKA1', 'baseline': {'assets': 488, 'payload_bytes': len(old), 'crc32': '53dcc3a5', 'pack_sha256': sha256(baseline_pack)},
              'assets': 636, 'payload_bytes': len(payload), 'file_bytes': len(pack), 'crc32': f'{crc:08x}', 'pack_sha256': sha256(pack),
              'retired_enemy_assets': list(RETIRED), 'retired_bytes': 759360, 'replacement_bytes': 428864,
              'unchanged_non_enemy_assets': unchanged, 'pixel_exact_reference_frames': len(reference_records), 'distinct_body_pose_pngs': len(set(png_hashes)),
              'embedded_fallback_bytes': len(fallback), 'body_decode_workspace_bytes': 13760, 'framebuffer_bytes': 153600,
              'known_psram_bytes': len(payload) + 153600 + 13760, 'theoretical_8mib_headroom_bytes': 8388608 - len(payload) - 153600 - 13760,
              'hardware_measured': False, 'effect_family_order': list(FAMILIES), 'reference_frames': reference_records, 'catalog': records}
    return BuildResult(bytes(pack), metadata, bytes(fallback), catalog_text(metadata, fallback, crc), descriptor_text(enemies), report)




def repack_exports(source_directory, write=True):
    """Reproduce the normalized export bundle from the original extracted ZIP.

    Only files listed in the frozen provenance record are read. Every source
    and the final compressed bundle must match the retained delivery checksums.
    """
    source = Path(source_directory).resolve()
    info = json.loads((ASSETS / 'provenance.json').read_text())['exports_bundle']
    buffer = io.BytesIO()
    with tarfile.open(fileobj=buffer, mode='w', format=tarfile.USTAR_FORMAT) as tf:
        for name, expected in sorted(info['files'].items()):
            path = (source / name).resolve()
            require(path.is_relative_to(source), 'Unsafe export source path')
            data = path.read_bytes()
            verify_file(data, expected, name)
            member = tarfile.TarInfo(name)
            member.size = len(data)
            member.mode = 0o644
            tf.addfile(member, io.BytesIO(data))
    compressed = bytearray(gzip.compress(buffer.getvalue(), compresslevel=9, mtime=0))
    compressed[9] = 255  # Normalize gzip OS byte across Python/platform versions.
    compressed = bytes(compressed)
    verify_file(compressed, info, info['file'])
    if write:
        (ASSETS / info['file']).write_bytes(compressed)
    return compressed


def extract_reference(directory):
    """Materialize validated exports and readable metadata for native test tools.

    The destination is a package root, so files live under exports/enemies/ and
    exports/effects/, matching the original delivery. No tar extractall is used.
    """
    destination = Path(directory).resolve()
    files, enemies = load_exports()
    for name, data in files.items():
        path = (destination / name).resolve()
        require(path.is_relative_to(destination), 'Unsafe reference export path')
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    # Copy original aggregate/effect manifests unchanged.
    for path in (ASSETS / 'source/exports').rglob('*.json'):
        target = destination / 'exports' / path.relative_to(ASSETS / 'source/exports')
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(path.read_bytes())
    # The roster contains the complete per-enemy record. Emit a small TSV as well
    # so C++ tests need no JSON library or list of externally supplied paths.
    rows = ['id\tslug\tanchor_x\tanchor_y\tanchor_mode\tfamily\tpalette_asset\tpose_assets']
    for e in enemies:
        i = e['id']
        folder = destination / f'exports/enemies/{i:02d}_{e["slug"]}'
        (folder / 'manifest.json').write_text(json_text(e))
        rows.append('\t'.join(map(str, [i, e['slug'], *e['root_anchor'], e['anchor_mode'], e['attack_kind'], 600 + i,
                                     ','.join(map(str, BODY_SLOTS[i * 4:i * 4 + 4]))])))
    (destination / 'enemies.tsv').write_text('\n'.join(rows) + '\n')
    rows = ['id\tfamily\tpalette_asset\tframe_assets']
    for k, family in enumerate(FAMILIES):
        rows.append(f'{k}\t{family}\t{629+k}\t' + ','.join(str(544 + k * 8 + f) for f in range(8)))
    (destination / 'effects.tsv').write_text('\n'.join(rows) + '\n')
    return len(files)


def generated_files(result):
    return {CATALOG_PATH: result.catalog, DESCRIPTOR_PATH: result.descriptors, REPORT_PATH: json_text(result.report)}


def verify_generated(result):
    for path, expected in generated_files(result).items():
        require(path.exists() and path.read_text() == expected, f'Generated file is stale: {path.relative_to(ROOT)}; run tools/prepare_enemy_art.py')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Validate every source and generated file without writing')
    parser.add_argument('--output', type=Path, help='Optionally emit a PKA1 package at this path')
    parser.add_argument('--extract-reference', type=Path, help='Extract validated compact/RGB565/PNG references and manifests for native tests')
    parser.add_argument('--repack-source', type=Path, help='Reproduce exports.tar.gz from the original extracted source package')
    args = parser.parse_args()
    if args.repack_source:
        repack_exports(args.repack_source, write=not args.check)
    result = build()
    if args.check:
        verify_generated(result)
    else:
        for path, data in generated_files(result).items():
            path.write_text(data)
    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_bytes(result.pack)
    if args.extract_reference:
        count = extract_reference(args.extract_reference)
        print(f'Extracted {count} validated reference files to {args.extract_reference}')
    print(f'PKA1: {result.report["assets"]} assets, {result.report["payload_bytes"]} payload bytes, CRC32 {result.report["crc32"]}')
    print('428 non-enemy payloads/fallbacks unchanged; 172 reference frames pixel-exact; 116 distinct body pose PNGs.')
    print(f'SHA-256: {result.report["pack_sha256"]}')


if __name__ == '__main__':
    main()
