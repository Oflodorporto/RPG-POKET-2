             'Cópia do aviso original: `licenses/CC-BY-3.0-upstream.txt`.', '',
             'Alterações: geometria normalizada pelo Iconify; seleção, cor, rasterização, contorno, destaque superior e quantização indexed4/RGB565 para RPG POKET.',
             'Nenhum endosso dos autores é sugerido. A licença do software/API Iconify não licencia estas imagens.',
