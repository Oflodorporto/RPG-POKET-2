#!/usr/bin/env python3
"""Offline, deterministic Game Icons pack build (Python standard library only).

Uses the existing game's transparent RGB565 key and indexed4 codec contract.
No source download, SVG renderer, image library, card mutation, or firmware inclusion.
"""
import argparse
from dataclasses import dataclass
import gzip
import io
import json
from pathlib import Path
import struct
import zlib

from fetch_public_api_icons import BASE, ROOT, json_bytes, load_lock, require, retained_files, sha, verify_files
from prepare_enemy_art import decode_idx4

SIZES = (24, 32)
KEY = 0xf81f
RGB = ('ff00ff', '131b25', '303a46', 'c69951', 'f4d899', 'a98958', 'edd9a2',
       'e66c37', 'ffcb78', 'baa3e8', 'efe1ff', '69b6c9', 'c5f1ed', '73b89b', 'cef0be', 'e7e2cc')
TONES = {'equipment': (3, 4), 'camp': (5, 6), 'fire': (7, 8), 'lightning': (9, 10), 'ice': (11, 12), 'ward': (13, 14)}


def rgb565(value):
    r, g, b = bytes.fromhex(value)
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


PALETTE = struct.pack('<16H', *(rgb565(c) for c in RGB))


def load_masks(lock, base=BASE):
    raster = json.loads((base / 'raster-lock.json').read_text())
    require(raster['schema_version'] == 1 and raster['source_subset_sha256'] == lock['iconify']['subset_sha256'], 'Stale raster lock')
    require(set(raster['exports']) == {r['slug'] for r in lock['icons']}, 'Missing or extra raster')
    masks = {}
    for row in lock['icons']:
        slug = row['slug']
        item = raster['exports'][slug]
        require(item['file'] == f'sources/masks/{slug}.mask8.gz', 'Unsafe raster path')
        require(item['width'] == item['height'] == 128 and item['decoded_bytes'] == 16384, 'Unexpected raster geometry')
        require(item['body_sha256'] == row['body_sha256'], 'Stale raster geometry')
        encoded = (base / item['file']).read_bytes()
        require(len(encoded) < 20000 and sha(encoded) == item['file_sha256'], 'Changed raster archive')
        with gzip.GzipFile(fileobj=io.BytesIO(encoded)) as stream:
            data = stream.read(16385)
        require(len(data) == 16384 and sha(data) == item['alpha_sha256'], 'Changed raster pixels')
        masks[slug] = data
    return masks


def coverage(mask, size):
    """Exact integer area average; no Pillow/version-dependent resizing at build time."""
    require(len(mask) == 128 * 128 and size in SIZES, 'Unsupported mask geometry')
    # Two pixels are reserved for a one-pixel outline and a transparent safety border.
    inside = size - 4
    result = [[False] * size for _ in range(size)]
    for y in range(inside):
        y0, y1 = y * 128, (y + 1) * 128
        for x in range(inside):
            x0, x1 = x * 128, (x + 1) * 128
            total = 0
            for sy in range(y0 // inside, (y1 + inside - 1) // inside):
                wy = min(y1, (sy + 1) * inside) - max(y0, sy * inside)
                for sx in range(x0 // inside, (x1 + inside - 1) // inside):
                    wx = min(x1, (sx + 1) * inside) - max(x0, sx * inside)
                    total += mask[sy * 128 + sx] * wx * wy
            result[y + 2][x + 2] = total >= 96 * 128 * 128
    return result


def encode(mask, size, tone):
    shape = coverage(mask, size)
    color, highlight = TONES[tone]
    pixels = []
    for y in range(size):
        for x in range(size):
            if shape[y][x]:
                pixels.append(highlight if y > 0 and not shape[y - 1][x] else color)
            elif any(shape[yy][xx] for yy in range(max(0, y - 1), min(size, y + 2))
                     for xx in range(max(0, x - 1), min(size, x + 2))):
                pixels.append(1)
            else:
                pixels.append(0)
    return bytes((pixels[i] << 4) | pixels[i + 1] for i in range(0, len(pixels), 2))


def png_rgba(decoded, width, height):
    """Small deterministic PNG writer for actual quantized pixels; no artwork renderer."""
    def chunk(kind, data):
        return struct.pack('>I', len(data)) + kind + data + struct.pack('>I', zlib.crc32(kind + data))
    colors = struct.unpack('<' + str(width * height) + 'H', decoded)
    rows = bytearray()
    for y in range(height):
        rows.append(0)
        for color in colors[y * width:(y + 1) * width]:
            rows.extend((color >> 11 << 3, ((color >> 5) & 63) << 2, (color & 31) << 3, 0 if color == KEY else 255))
    return (b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', width, height, 8, 6, 0, 0, 0)) +
            chunk(b'IDAT', zlib.compress(bytes(rows), 9)) + chunk(b'IEND', b''))


def identifier(slug):
    return ''.join(word.title() for word in slug.split('-'))


def header(lock, planes):
    lines = ['#pragma once', '#include <stdint.h>',
             '// Generated by tools/prepare_public_api_icons.py. Optional, not included by the game.',
             '// Game Icons: CC BY 3.0. See assets/public-api-icons1/CREDITS.md for individual artists.',
             'namespace publicApiIcons {', 'enum class Icon : uint8_t {']
    lines += [f"  {identifier(r['slug'])}={r['id']}," for r in lock['icons']]
    lines += ['  Count=16', '};', 'inline constexpr unsigned COUNT=16;',
              'inline constexpr uint16_t TRANSPARENT=0xf81f;',
              'inline constexpr uint8_t palette[32]={' + ','.join(map(str, PALETTE)) + '};']
    for size in SIZES:
        lines += [f'inline constexpr uint8_t plane{size}[COUNT][{size * size // 2}]={{']
        for row in lock['icons']:
            data = planes[(row['slug'], size)]
            lines += ['{ // ' + row['slug']]
            lines += [','.join(map(str, data[i:i + 32])) + ',' for i in range(0, len(data), 32)]
            lines += ['},']
        lines += ['};']
    lines += ['inline constexpr unsigned FLASH_BYTES=sizeof(palette)+sizeof(plane24)+sizeof(plane32);',
              'static_assert(FLASH_BYTES==12832,"Offline icon pack storage contract");', '}']
    return ('\n'.join(lines) + '\n').encode()


