"""Convert the approved proportional27x20 map tent to a const RGB565 sprite."""
from pathlib import Path
from PIL import Image
import argparse
import hashlib
ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'assets/reusable/equipment01/map/tent_canvas_27x20.png'
HEADER=ROOT/'firmware/RPG_POKET_2/TentMarker.h'
im=Image.open(SOURCE).convert('RGBA')
assert im.size==(27,20)
assert set(im.getchannel('A').getdata())=={0,255}
pixels=[]
for r,g,b,a in im.getdata():
    value=((r>>3)<<11)|((g>>2)<<5)|(b>>3)
    assert not a or value!=0xf81f
    pixels.append(value if a else 0xf81f)
text='''#pragma once
#include <stdint.h>
// Approved proportional equipment tent: open entrance, fabric side, ropes/pegs.
// Generated by tools/prepare_tent_marker.py. Const flash only, no art-pak/PSRAM.
// Source SHA-256: %s
namespace tentMarker {
constexpr int Width=27,Height=20;
constexpr uint16_t Transparent=0xf81f;
constexpr uint16_t pixels[Width*Height]={
'''%hashlib.sha256(SOURCE.read_bytes()).hexdigest()
text+='\n'.join(' '+','.join(f'0x{v:04x}' for v in pixels[y*27:(y+1)*27])+',' for y in range(20))
text+='''
};
template<class C>void draw(C& c,int x,int y){
 // Coalesce adjacent RGB565 colours; fixed27x20 bounds, no temporary buffer.
 for(int row=0;row<Height;++row)for(int col=0;col<Width;){
  uint16_t color=pixels[row*Width+col];int end=col+1;
  while(end<Width&&pixels[row*Width+end]==color)++end;
  if(color!=Transparent)c.fillRect(x+col,y+row,end-col,1,color);
  col=end;
 }
}
}
'''
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check',action='store_true')
args=parser.parse_args()
if args.check:assert HEADER.read_text()==text, 'Regenerate the marker with tools/prepare_tent_marker.py'
else:HEADER.write_text(text)
print('PASS: authored27x20 marker, proportional opaque25x18, binary alpha,1080 const flash bytes and zero buffers')
