param([switch]$Check)
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing
function ConvertTo-Rgb565([int]$Red, [int]$Green, [int]$Blue) {
    return (($Red -shr 3) -shl 11) -bor (($Green -shr 2) -shl 5) -bor ($Blue -shr 3)
}
foreach ($vector in @(@(255,0,0,63488),@(0,255,0,2016),@(0,0,255,31),@(255,255,255,65535),@(0,0,0,0))) {
    if ((ConvertTo-Rgb565 $vector[0] $vector[1] $vector[2]) -ne $vector[3]) { throw 'RGB565 standard vector failed' }
}
$root = Split-Path $PSScriptRoot -Parent
$names = @('oak_staff','iron_sword','iron_spear','iron_axe','leather_armor','simple_amulet')
$manifest = Get-Content -LiteralPath (Join-Path $root 'assets/reusable/equipment01/manifest.json') -Raw | ConvertFrom-Json
$images = @(); $masks = @()
foreach ($name in $names) {
    $entry = $manifest.assets | Where-Object { $_.id -eq $name }
    $path = Join-Path $root ('assets/reusable/equipment01/png32/' + $name + '.png')
    if ((Get-FileHash -LiteralPath $path -Algorithm SHA256).Hash.ToLowerInvariant() -ne $entry.exports.'32'.sha256) { throw "Source hash changed: $name" }
    $bitmap = [System.Drawing.Bitmap]::new($path)
    try {
        if ($bitmap.Width -ne 32 -or $bitmap.Height -ne 32) { throw "Wrong dimensions: $name" }
        $pixels = [System.Collections.Generic.List[string]]::new(); $mask = [byte[]]::new(128)
        for ($y = 0; $y -lt 32; $y++) { for ($x = 0; $x -lt 32; $x++) {
            $color = $bitmap.GetPixel($x, $y); $index = $y * 32 + $x
            if ($color.A -ne 0 -and $color.A -ne 255) { throw "Non-binary alpha: $name" }
            $rgb = 0
            if ($color.A -eq 255) {
                $rgb = ConvertTo-Rgb565 $color.R $color.G $color.B
                $mask[$index -shr 3] = $mask[$index -shr 3] -bor (1 -shl ($index -band 7))
            }
            $pixels.Add(('0x{0:x4}' -f $rgb))
        } }
        $images += '{' + ($pixels -join ',') + '}'
        $masks += '{' + (($mask | ForEach-Object { '0x{0:x2}' -f $_ }) -join ',') + '}'
    } finally { $bitmap.Dispose() }
}
$header = @'
// Generated by tools/prepare_equipment_icons.ps1 from equipment01/png32.
// RGB565 plus binary alpha: opaque black is never used as a transparency key.
#pragma once
#include <stdint.h>
namespace equipmentArt {
'@
$header += "`ninline constexpr uint16_t pixels[6][1024]={`n" + ($images -join ",`n") + "`n};`n"
$header += "inline constexpr uint8_t alpha[6][128]={`n" + ($masks -join ",`n") + "`n};`n"
$header += @'
static_assert(sizeof(pixels)+sizeof(alpha)==13056,"Equipment flash budget changed");
template<class C> void draw(C& c,unsigned family,int x,int y){
 if(family>=6)return;
 for(unsigned i=0;i<1024;++i)if(alpha[family][i/8]&(1u<<(i%8)))c.fillRect(x+int(i%32),y+int(i/32),1,1,pixels[family][i]);
}
}
'@
$header += "`n"
$target = Join-Path $root 'firmware/RPG_POKET_2/EquipmentIcons.h'
if ($Check) {
    if ([System.IO.File]::ReadAllText($target).Replace("`r`n","`n") -cne $header) { throw 'Generated equipment header differs' }
} else { [System.IO.File]::WriteAllText($target, $header, [System.Text.UTF8Encoding]::new($false)) }
Write-Output 'PASS: six source hashes, 32x32, binary alpha, RGB565, 13056 flash bytes; no artes.pak or PSRAM change'
